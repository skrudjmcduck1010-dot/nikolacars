<?php

// Exercise the real entry point in isolated processes, with no database or API.
$source = file_get_contents(__DIR__.'/../public/index.php');
$temporaryDirectory = realpath(__DIR__.'/../.codex-tmp');
if ($temporaryDirectory === false) {
    mkdir(__DIR__.'/../.codex-tmp', 0777, true);
    $temporaryDirectory = realpath(__DIR__.'/../.codex-tmp');
}
$fixtureRoot = $temporaryDirectory.DIRECTORY_SEPARATOR.'front-controller-'.bin2hex(random_bytes(8));
mkdir($fixtureRoot);

function writeFrontFixture(string $path, string $content): void
{
    if (! is_dir(dirname($path))) {
        mkdir(dirname($path), 0777, true);
    }
    file_put_contents($path, $content);
}

$autoload = <<<'PHP'
<?php
namespace Illuminate\Http;
class Request
{
    public static function capture(): string
    {
        return 'captured-request';
    }
}
PHP;

$bootstrap = <<<'PHP'
<?php
return new class {
    public function handleRequest(string $request): void
    {
        if ($request !== 'captured-request') {
            throw new RuntimeException('Request was not captured.');
        }
        echo __FIXTURE_RESULT__;
    }
};
PHP;

$cases = [
    ['local', ['local'], null, 'handled-local'],
    ['hosted', ['hosted'], null, 'handled-hosted'],
    ['both', ['local', 'hosted'], null, 'handled-hosted'],
    ['local-maintenance', ['local'], 'local', 'maintenance-local'],
    ['hosted-maintenance', ['hosted'], 'hosted', 'maintenance-hosted'],
    ['inactive-local-maintenance', ['local', 'hosted'], 'local', 'handled-hosted'],
];

try {
    foreach ($cases as [$name, $layouts, $maintenanceLayout, $expected]) {
        $caseRoot = $fixtureRoot.'/'.$name;
        writeFrontFixture($caseRoot.'/public/index.php', $source);
        foreach ($layouts as $layout) {
            $appRoot = $layout === 'hosted' ? $caseRoot.'/public/laravel_app' : $caseRoot;
            writeFrontFixture($appRoot.'/vendor/autoload.php', $autoload);
            writeFrontFixture($appRoot.'/bootstrap/app.php', str_replace(
                '__FIXTURE_RESULT__', var_export('handled-'.$layout, true), $bootstrap,
            ));
            if ($maintenanceLayout === $layout) {
                writeFrontFixture($appRoot.'/storage/framework/maintenance.php',
                    '<?php echo '.var_export('maintenance-'.$layout, true).'; exit;');
            }
        }

        $process = proc_open([PHP_BINARY, $caseRoot.'/public/index.php'], [
            0 => ['pipe', 'r'], 1 => ['pipe', 'w'], 2 => ['pipe', 'w'],
        ], $pipes, $caseRoot);
        if (! is_resource($process)) {
            throw new RuntimeException('Could not start fixture process.');
        }
        fclose($pipes[0]);
        $output = stream_get_contents($pipes[1]);
        $errors = stream_get_contents($pipes[2]);
        fclose($pipes[1]);
        fclose($pipes[2]);
        $exitCode = proc_close($process);
        if ($exitCode !== 0 || $output !== $expected || $errors !== '') {
            throw new RuntimeException("Entry point failed for $name: $output $errors");
        }
        echo "PASS $name: $expected\n";
    }
} finally {
    // Remove only fixtures generated by this test, never the shared temp folder.
    $resolvedRoot = realpath($fixtureRoot);
    if ($resolvedRoot === false
        || ! str_starts_with($resolvedRoot, $temporaryDirectory.DIRECTORY_SEPARATOR)
        || ! str_starts_with(basename($resolvedRoot), 'front-controller-')) {
        throw new RuntimeException('Unsafe fixture cleanup path.');
    }
    $entries = new RecursiveIteratorIterator(
        new RecursiveDirectoryIterator($resolvedRoot, FilesystemIterator::SKIP_DOTS),
        RecursiveIteratorIterator::CHILD_FIRST,
    );
    foreach ($entries as $entry) {
        $resolvedEntry = $entry->getRealPath();
        if ($resolvedEntry === false || ! str_starts_with($resolvedEntry, $resolvedRoot.DIRECTORY_SEPARATOR)) {
            throw new RuntimeException('Fixture cleanup escaped its directory.');
        }
        $entry->isDir() ? rmdir($entry->getPathname()) : unlink($entry->getPathname());
    }
    rmdir($resolvedRoot);
}

echo "All front-controller regression checks passed.\n";
